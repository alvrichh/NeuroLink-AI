#!/usr/bin/env node
/**
 * Sync the official NeuroLink AI identity into the web app.
 *
 * /assets/branding is the single source of truth. This script copies the logo
 * files and the canonical CSS tokens verbatim, and generates a typed module
 * with the raw colour values (for canvas drawing) and each logo file's pixel
 * size (so <img> tags reserve the right space).
 * It fails loudly if tokens.css and tokens.json ever disagree.
 */
import { copyFile, cp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const app = resolve(here, "..");
const branding = resolve(app, "../../assets/branding");

const tokensCss = await readFile(resolve(branding, "tokens.css"), "utf8");
const tokens = JSON.parse(await readFile(resolve(branding, "tokens.json"), "utf8"));

const expected = {
  "--nl-white": tokens.palette.white,
  "--nl-navy": tokens.palette.navy,
  "--nl-blue": tokens.palette.electricBlue,
  "--nl-cyan": tokens.palette.cyan,
};
for (const [name, hex] of Object.entries(expected)) {
  const match = tokensCss.match(new RegExp(`${name}:\\s*(#[0-9a-fA-F]{6})`));
  if (!match || match[1].toUpperCase() !== String(hex).toUpperCase()) {
    console.error(`Brand token mismatch for ${name}: tokens.css=${match?.[1]} tokens.json=${hex}`);
    process.exit(1);
  }
}

const hexToRgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16));

// Start from an empty folder so a retired logo file is never left behind.
await rm(resolve(app, "public/brand"), { recursive: true, force: true });
await mkdir(resolve(app, "public/brand"), { recursive: true });
await mkdir(resolve(app, "src/styles/brand"), { recursive: true });

/** Official logo files, by role. */
const logoFiles = {
  symbol: "neurolink-ai-symbol.webp",
  wordmark: "neurolink-ai-wordmark.webp",
  lockup: "neurolink-ai-lockup.webp",
};

/** Favicon and app icons: fixed names and sizes, copied as a set. */
const iconFiles = ["favicon.ico", "icon-32.png", "icon-192.png", "icon-512.png", "apple-touch-icon.png"];

/** Pixel size of a PNG or WebP file, read from its header. */
function imageSize(buffer, file) {
  if (buffer.toString("latin1", 1, 4) === "PNG") {
    return { width: buffer.readUInt32BE(16), height: buffer.readUInt32BE(20) };
  }
  const chunk = buffer.toString("latin1", 12, 16);
  if (chunk === "VP8 ") {
    return { width: buffer.readUInt16LE(26) & 0x3fff, height: buffer.readUInt16LE(28) & 0x3fff };
  }
  if (chunk === "VP8L") {
    const bits = buffer.readUInt32LE(21);
    return { width: (bits & 0x3fff) + 1, height: ((bits >> 14) & 0x3fff) + 1 };
  }
  if (chunk === "VP8X") {
    return { width: buffer.readUIntLE(24, 3) + 1, height: buffer.readUIntLE(27, 3) + 1 };
  }
  throw new Error(`Unsupported image format: ${file}`);
}

const assets = {};
for (const [role, file] of Object.entries(logoFiles)) {
  const source = resolve(branding, file);
  assets[role] = { file, ...imageSize(await readFile(source), file) };
  await copyFile(source, resolve(app, "public/brand", file));
}

for (const file of iconFiles) {
  await readFile(resolve(branding, "icons", file)); // fail loudly if one is missing
}
await cp(resolve(branding, "icons"), resolve(app, "public/brand/icons"), { recursive: true });
// Browsers and crawlers also ask for /favicon.ico at the site root.
await copyFile(resolve(branding, "icons/favicon.ico"), resolve(app, "public/favicon.ico"));
await copyFile(resolve(branding, "tokens.css"), resolve(app, "src/styles/brand/tokens.css"));

const ts = `// GENERATED by scripts/sync-brand.mjs from /assets/branding/tokens.json — do not edit.
export const brand = {
  name: ${JSON.stringify(tokens.brand)},
  version: ${JSON.stringify(tokens.version)},
  hex: ${JSON.stringify(tokens.palette)},
  rgb: {
    navy: ${JSON.stringify(hexToRgb(tokens.palette.navy))},
    electricBlue: ${JSON.stringify(hexToRgb(tokens.palette.electricBlue))},
    cyan: ${JSON.stringify(hexToRgb(tokens.palette.cyan))},
    white: ${JSON.stringify(hexToRgb(tokens.palette.white))},
  },
  /** Official logo files (served from /brand/) with their pixel sizes. */
  assets: ${JSON.stringify(assets)},
} as const;
`;
await writeFile(resolve(app, "src/styles/brand/tokens.ts"), ts);
console.log("Brand assets synced from assets/branding (logos, tokens.css, tokens.ts).");
